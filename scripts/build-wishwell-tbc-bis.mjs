// Builds wow-addon/WishwellTBC/DataBis.lua: best-in-slot gear lists for each talent build and
// phase, for Wisp's "BiS check".
//   node scripts/build-wishwell-tbc-bis.mjs
//
// The lists are the gear presets of the wowsims TBC simulator (github.com/wowsims/tbc, MIT
// licence): the sets its authors and the class communities settled on for each phase. It has
// no healing simulators, so there are no lists for healers.
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs'
import { tmpdir } from 'node:os'
import { join } from 'node:path'

const WOWSIMS = 'https://raw.githubusercontent.com/wowsims/tbc/master/ui'
const OUT = new URL('../wow-addon/WishwellTBC/DataBis.lua', import.meta.url)
const CACHE = join(tmpdir(), 'wishwell-wowsims-tbc')

// Each talent build (the keys in DataTalents.lua): the wowsims folder, and a word its preset
// names must carry when one folder holds several builds. Builds wowsims has no set for
// borrow the nearest one (marked close = the build it was made for).
const BUILDS = {
  DRUID: { balance: ['balance_druid'], cat: ['feral_druid'], bear: ['feral_tank_druid'] },
  HUNTER: { bm: ['hunter', 'BM'], mm: ['hunter', 'BM', 'Beast Mastery'], sv: ['hunter', 'SV'] },
  MAGE: { arcane: ['mage', 'Arcane'], fire: ['mage', 'Fire'], frost: ['mage', 'Frost'] },
  PALADIN: { ret: ['retribution_paladin'], prot: ['protection_paladin'] },
  PRIEST: { shadow: ['shadow_priest'] },
  ROGUE: { combat: ['rogue'], maces: ['rogue', null, 'Combat (Swords)'], mutilate: ['rogue', null, 'Combat (Swords)'] },
  SHAMAN: { enh: ['enhancement_shaman'], ele: ['elemental_shaman'] },
  WARLOCK: { destro: ['warlock', 'Destro'], aff: ['warlock', 'Destro', 'Destruction'], demo: ['warlock', 'Destro', 'Destruction'] },
  WARRIOR: { fury: ['warrior', 'Fury'], arms: ['warrior', 'Arms'], prot: ['protection_warrior'] },
}

async function get(folder) {
  mkdirSync(CACHE, { recursive: true })
  const file = join(CACHE, `${folder}.ts`)
  if (existsSync(file) && !process.argv.includes('--refresh')) return readFileSync(file, 'utf8')
  const res = await fetch(`${WOWSIMS}/${folder}/presets.ts`)
  if (!res.ok) throw new Error(`${folder}: ${res.status}`)
  const text = await res.text()
  writeFileSync(file, text)
  return text
}

// Every gear preset in one file: { name, phase, side, items: [item id, ...] }.
function presets(src) {
  const found = []
  const marker = 'EquipmentSpec.fromJsonString(`'
  let at = 0
  for (;;) {
    const gear = src.indexOf(marker, at)
    if (gear < 0) break
    const end = src.indexOf('`', gear + marker.length)
    const before = src.slice(Math.max(0, gear - 300), gear)
    const name = (before.match(/name:\s*'([^']+)'[^']*$/) || [])[1]
    const items = JSON.parse(src.slice(gear + marker.length, end)).items.map((item) => item.id).filter(Boolean)
    if (name && items.length) {
      const phase = /pre-?raid/i.test(name) ? 0 : Number((name.match(/\bP(\d)\b/) || [])[1])
      const side = /Alliance/.test(name) ? 'A' : /Horde/.test(name) ? 'H' : ''
      if (Number.isInteger(phase)) found.push({ name, phase, side, items })
    }
    at = end + 1
  }
  return found
}

const lines = [
  '-- Generated by scripts/build-wishwell-tbc-bis.mjs. Do not edit by hand.',
  '-- Best-in-slot gear by talent build and phase, from the gear presets of the wowsims TBC',
  '-- simulator (github.com/wowsims/tbc, MIT licence). phase 0 is before raiding.',
  '-- side: "A" or "H" where the list differs by faction. close: the build the list was made for,',
  '-- where this build borrows it.',
  'WishwellTBCData = WishwellTBCData or {}',
  'WishwellTBCData.bis = {',
]
let count = 0
for (const [cls, builds] of Object.entries(BUILDS)) {
  lines.push(`  ${cls} = {`)
  for (const [key, [folder, word, close]] of Object.entries(builds)) {
    const sets = presets(await get(folder)).filter((set) => !word || set.name.includes(word))
    if (!sets.length) throw new Error(`${cls} ${key}: no presets`)
    sets.sort((a, b) => a.phase - b.phase || a.side.localeCompare(b.side))
    lines.push(`    ${key} = {`)
    for (const set of sets) {
      const parts = [`phase = ${set.phase}`]
      if (set.side) parts.push(`side = "${set.side}"`)
      if (close) parts.push(`close = "${close}"`)
      parts.push(`items = { ${set.items.join(', ')} }`)
      lines.push(`      { ${parts.join(', ')} },`)
      count++
    }
    lines.push('    },')
  }
  lines.push('  },')
}
lines.push('}', '')
writeFileSync(OUT, lines.join('\n'))
console.log(`wrote ${count} gear lists`)
